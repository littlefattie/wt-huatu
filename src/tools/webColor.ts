export const isValidColor = (color?: string): string | undefined => {
  if (!color) return undefined;
  color = color.trim().toLowerCase();
  if (color === "cc") return "currentColor";    // Some shortcut for 'currentColor'
  if (color === "currentcolor") return "currentColor";
  if (color === "none") return "none";
  if (color === "ctxstroke") return "context-stroke";
  if (color === "ctxfill") return "context-fill";
  if (webColorNames.find(c => c === color)) return color;
  if ( WT_REGEX.COLOR_CODE_3.test(color)
    || WT_REGEX.COLOR_CODE_6.test(color)
    || WT_REGEX.COLOR_CODE_8.test(color)) return color;
  return undefined;
}

